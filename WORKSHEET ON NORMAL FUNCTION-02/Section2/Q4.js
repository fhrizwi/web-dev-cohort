// Section 2: Arrow Function with One Parameter

// Q4. Convert this function to an arrow function with one parameter (remove unnecessary 
// parentheses): 
// function greet(name) { 
// return `Hello, ${name}!`; 
// } 

const greet = name => `Hello, ${name}!`;
console.log(greet("Faizul")); // Output: Hello, Faizul!
