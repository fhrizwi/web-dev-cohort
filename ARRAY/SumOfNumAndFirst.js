const SumOfFirstElement=(arr, num)=>{
    return arr[0]+num
}
console.log(SumOfFirstElement([4,5,6],7))  //4+7=11 //Ques:first sum add krna




const SumOfLastElement = (arr, num) => {
    return arr[arr.length - 1] + num;
}

console.log(SumOfLastElement([4, 5, 6], 7)); // 6 + 7 = 13 //Ques:last element add krna
