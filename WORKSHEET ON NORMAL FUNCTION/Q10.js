// 10. Write a function which takes in a number as input and returns it after multiplying by 
// 10. 

function multiplyByTen(num) {
    return num * 10;
}


console.log(multiplyByTen(5));    // Output: 50
console.log(multiplyByTen(12));   // Output: 120
console.log(multiplyByTen(-3));   // Output: -30
