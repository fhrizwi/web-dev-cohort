// 9. Write a function that takes a number as input and determines if it is a multiple of 3

function multipleOfThree(num){
    if(num%3===0){
        console.log("Yes This Number Is Multiple of 3")
    }else{
        console.log("Not Multiple of 3")
    }
}
multipleOfThree(6)
multipleOfThree(5)
multipleOfThree(45)
multipleOfThree(100)
multipleOfThree(1)
